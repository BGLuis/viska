/// Teste de Decapsulamento e Rejeição Implícita FIPS 203.
///
/// Verifica que:
/// 1. Decapsular o ciphertext legítimo com a chave privada correta devolve exatamente o segredo compartilhado.
/// 2. Adulterar um único byte do ciphertext NÃO causa pânico nem erro explícito, mas produz um segredo
///    pseudoaleatório diferente (rejeição implícita exigida pelo FIPS 203).
#[test]
fn nist_fips203_decapsulate_and_implicit_rejection() {
    let seed = [0x5Au8; 64];
    let keypair = mlkem768::generate_key_pair(seed);

    let randomness = [0xA5u8; 32];
    let (ct, ss) = mlkem768::encapsulate(keypair.public_key(), randomness);

    // Decapsulação correta
    let recovered_ss = mlkem768::decapsulate(keypair.private_key(), &ct);
    assert_eq!(ss.as_slice(), recovered_ss.as_slice());

    // Ciphertext adulterado -> rejeição implícita
    let mut bad_ct_bytes = *ct.as_slice();
    bad_ct_bytes[42] ^= 0x01;
    let bad_ct = MlKem768Ciphertext::from(bad_ct_bytes);

    let rejected_ss = mlkem768::decapsulate(keypair.private_key(), &bad_ct);
    assert_ne!(ss.as_slice(), rejected_ss.as_slice(), "rejeição implícita falhou em produzir segredo divergente");
}
